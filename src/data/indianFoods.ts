export const indianFoods: Food[] = rows.map(
  ([id, name, category, serving, calories, protein, carbs, fat, aliases]) => ({
    id: "in-" + id,
    name,
    category,
    serving,
    calories,
    protein,
    carbs,
    fat,
    aliases: aliases.split(" "),
    vegetarian: category !== "Non-vegetarian",
    nutritionKnown: true,
    source:
      "Daywell indicative preparation estimate · verify size, ingredients, and oil; not IFCT laboratory data",
  }),
);
export function foodMatches(food: Food, query: string) {
  return query
    .toLowerCase()
    .trim()
    .split(/\s+/)
    .every((token) =>
      `${food.name} ${food.serving} ${food.category || ""} ${(food.aliases || []).join(" ")}`
        .toLowerCase()
        .includes(token),
    );
}
